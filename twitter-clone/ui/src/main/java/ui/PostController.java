  /** Updates the retweet UI elements when the retweet button is pressed. */
  @FXML
  public void updateRetweets() {
    if (currentPost == null || retweetBtn == null) {
      return;
    }

    final int MAX_MESSAGE_LEN = 280; // ⬅️ adjust as needed

    Dialog<String> dialog = new Dialog<>();
    dialog.setTitle("Retweet");
    dialog.setHeaderText("Add an optional message and confirm your retweet");

    ButtonType retweetBtnType = new ButtonType("Retweet", ButtonBar.ButtonData.OK_DONE);
    dialog.getDialogPane().getButtonTypes().addAll(retweetBtnType, ButtonType.CANCEL);

    TextArea messageArea = new TextArea();
    messageArea.setPromptText("Add a message (optional)");
    messageArea.setWrapText(true);
    messageArea.setPrefRowCount(3);

    Label counter = new Label();
    counter.textProperty().bind(javafx.beans.binding.Bindings.format("%d / %d",
        javafx.beans.binding.Bindings.length(messageArea.textProperty()), MAX_MESSAGE_LEN));
    BooleanBinding overLimit = javafx.beans.binding.Bindings.greaterThan(
        javafx.beans.binding.Bindings.length(messageArea.textProperty()), MAX_MESSAGE_LEN);
    counter.textFillProperty().bind(javafx.beans.binding.Bindings.when(overLimit)
        .then(javafx.scene.paint.Color.RED).otherwise(javafx.scene.paint.Color.GRAY));
    BooleanBinding isEmpty = javafx.beans.binding.Bindings.createBooleanBinding(
        () -> messageArea.getText().trim().isEmpty(), messageArea.textProperty());

    HBox counterBox = new HBox(counter);
    counterBox.setAlignment(javafx.geometry.Pos.BASELINE_RIGHT);
    counterBox.setPadding(new javafx.geometry.Insets(4, 0, 0, 0));

    VBox content = new VBox(8, messageArea, counterBox);
    content.setPrefWidth(420);
    dialog.getDialogPane().setContent(content);

    Node okButton = dialog.getDialogPane().lookupButton(retweetBtnType);
    okButton.disableProperty().bind(overLimit.or(isEmpty));

    javafx.application.Platform.runLater(messageArea::requestFocus);

    dialog.setResultConverter(btn -> (btn == retweetBtnType) ? messageArea.getText().trim() : null);

    Optional<String> result = dialog.showAndWait();
    result.ifPresent(this::onConfirmRetweetSafe);
  }

  private void onConfirmRetweetSafe(String msg) {
    UserResponse user = userService.getLoggedInUser();

    if (user.id().equals(currentPost.author().id())) {
      return;
    }

    if (msg == null) {
      msg = " ";
    }

    postService.createPost(msg, currentPost.id());

    if (retweetBtn != null) {
      retweetBtn.setText(currentPost.reTweets() + " 🔄");
      retweetBtn.setStyle("-fx-text-fill: cyan;");
    }

    try {
      App.setRoot("feed.fxml");
    } catch (IOException e) {
      e.printStackTrace();
    }
  }

  /**
   * Deletes the current post.
   * <p>
   * Currently not implemented.
   *
   * @throws UnsupportedOperationException always, until implemented
   */
  @FXML
  public void deletePostAction(javafx.event.ActionEvent event) {
    PostResponse postToDelete = null;

    Object source = event.getSource();
    if (source == deleteBtn) {
      postToDelete = currentPost;
    } else if (source == deleteOriginalBtn) {
      postToDelete = originalPost;
    }

    if (postToDelete == null)
      return;

    Dialog<ButtonType> dialog = new Dialog<>();
    dialog.setTitle("Delete Post");
    dialog.setHeaderText("Are you sure you want to delete this post?");
    dialog.getDialogPane().getButtonTypes().addAll(ButtonType.YES, ButtonType.CANCEL);

    Optional<ButtonType> result = dialog.showAndWait();
    if (result.isPresent() && result.get() == ButtonType.YES) {
      postService.deletePost(postToDelete.id());

      // Update inner content if original post deleted
      if (postToDelete == originalPost && contentLabel1 != null) {
        contentLabel1.setText("Original post deleted");
      }

      postService.notifyPostUpdated();
    }
  }
